import "server-only";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

/**
 * Where attachment bytes live. Locally that's a folder on disk (STORAGE_DIR, default
 * ./storage, git-ignored). On Azure this becomes a Blob Storage driver with the same three
 * calls; nothing else in the app touches files directly. Files are never served from a public
 * URL: they go through /api/attachments/[id], which checks who's asking.
 */
export interface FileStorage {
  put(key: string, bytes: Uint8Array): Promise<void>;
  get(key: string): Promise<Buffer | null>;
  delete(key: string): Promise<void>;
}

const KEY_PATTERN = /^[a-z0-9-]+(\/[A-Za-z0-9_-]+)*\.[a-z0-9]+$/;

/** Keys are generated by us, but check anyway so a bad key can never escape the folder. */
export function assertSafeKey(key: string): void {
  if (!KEY_PATTERN.test(key) || key.includes("..")) throw new Error(`Unsafe storage key: ${key}`);
}

class LocalDiskStorage implements FileStorage {
  constructor(private readonly root: string) {}

  private resolve(key: string) {
    assertSafeKey(key);
    const full = path.resolve(this.root, key);
    if (!full.startsWith(path.resolve(this.root) + path.sep)) throw new Error(`Unsafe storage key: ${key}`);
    return full;
  }

  async put(key: string, bytes: Uint8Array) {
    const full = this.resolve(key);
    await mkdir(path.dirname(full), { recursive: true });
    await writeFile(full, bytes, { flag: "wx" }); // never overwrite
  }

  async get(key: string) {
    try {
      return await readFile(this.resolve(key));
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === "ENOENT") return null;
      throw error;
    }
  }

  async delete(key: string) {
    await rm(this.resolve(key), { force: true });
  }
}

export const storage: FileStorage = new LocalDiskStorage(process.env.STORAGE_DIR ?? path.join(process.cwd(), "storage"));
